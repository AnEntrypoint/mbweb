#!/usr/bin/env bash
# Assemble the GitHub Pages site in site/ (PRD-05, PRD-06). Requires scripts/build-component.sh.
#
# site/ holds the page, its bundled JavaScript, the transpiled component core modules and the
# model manifest. The GGUF weights are not part of the site: the page fetches them at runtime (PRD-04).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SITE="$ROOT/site"
BUILD_JS="$ROOT/build/js"

[ -f "$BUILD_JS/motionbricks.js" ] || { echo "build-site: run scripts/build-component.sh first" >&2; exit 1; }

rm -rf "$SITE"
mkdir -p "$SITE/component" "$SITE/model"

# jco's default core-module loader has a Node-only branch (node:fs/promises). The page always
# supplies its own loader, so that branch never runs in the browser and stays external.
(cd "$ROOT" && npx --no-install esbuild web/app.mjs \
    --bundle --format=esm --platform=browser --target=es2022 --minify \
    --external:node:fs/promises \
    --outdir="$SITE" --entry-names=[name])

# Workers are classic scripts: the module-worker type is the one WebKit refuses to start in the smoke run.
(cd "$ROOT" && npx --no-install esbuild web/worker.mjs web/threads-worker.mjs \
    --bundle --format=iife --platform=browser --target=es2022 --minify \
    --external:node:fs/promises \
    --outdir="$SITE" --entry-names=[name])

cp "$ROOT/web/index.html" "$ROOT/web/style.css" "$SITE/"
cp "$ROOT/web/coi-sw.js" "$SITE/"
# The threaded core is a plain wasm module the inference worker loads directly (scripts/build-threads.sh).
THREADED="$ROOT/build/threads/motionbricks-threads.wasm"
[ -f "$THREADED" ] || { echo "build-site: run scripts/build-threads.sh first" >&2; exit 1; }
mkdir -p "$SITE/threads"
cp "$THREADED" "$SITE/threads/"
cp "$BUILD_JS"/*.wasm "$SITE/component/"
cp "$ROOT/model/manifest.json" "$SITE/model/manifest.json"
mkdir -p "$SITE/model/styles"
cp "$ROOT/web/model/styles/manifest.json" "$SITE/model/styles/"
# Kimodo clips generated by animation/build-clips.mjs: small, committed, and played as authored sequences.
if [ -d "$ROOT/web/model/clips" ]; then
    mkdir -p "$SITE/model/clips"
    cp "$ROOT"/web/model/clips/* "$SITE/model/clips/"
fi
# Pages serves files as-is; keep the empty marker so no path is filtered by Jekyll.
touch "$SITE/.nojekyll"

echo "build-site: $SITE" >&2
